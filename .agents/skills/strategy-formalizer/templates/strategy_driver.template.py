@dataclass
class Account:
    """
    Account-level inputs for sizing: capital and the per-trade loss fraction
    (parameter per_trade_loss_ratio). `size_from_risk` implements the "light
    position" constraint: contracts = floor(capital * ratio / (stop distance in
    price × multiplier)).

    用于仓位计算的账户信息：本金和单笔亏损占比（参数 per_trade_loss_ratio）。`size_from_risk`
    实现"轻仓"约束：手数 = floor(本金 × 比例 / (止损价差 × 合约乘数))。
    """
    capital: float
    per_trade_loss_ratio: float
    min_size: float = 1.0

    def size_from_risk(self, entry_price: float, stop: "StopDistance | float", instrument: Instrument) -> float:
        """
        Position size for a new entry given the stop distance. Returns 0 when
        the risk budget cannot afford one contract.

        根据止损距离计算新仓手数；风险预算不足一手时返回 0。
        """
        distance = stop_distance_in_price(entry_price, stop)
        if distance <= 0:
            return 0.0
        per_unit = distance * max(instrument.multiplier, 1e-12)
        size = math.floor(self.capital * self.per_trade_loss_ratio / per_unit)
        return float(size) if size >= self.min_size else 0.0


def stop_distance_in_price(entry_price: float, stop: "StopDistance | float") -> float:
    """
    Convert a StopDistance (points or percent) or a bare number of points into
    a price distance.

    把 StopDistance（点数或百分比）或裸点数转换成价格距离。
    """
    if isinstance(stop, (int, float)):
        return float(stop)
    return float(stop.value) if stop.unit == "points" else float(entry_price) * float(stop.value) / 100.0


def stop_price_from(entry_price: float, direction: Direction, stop: "StopDistance | float") -> float:
    """
    Initial stop price: below entry for a long, above for a short.

    初始止损价：多头在入场价之下，空头在入场价之上。
    """
    d = stop_distance_in_price(entry_price, stop)
    return entry_price - d if direction == "long" else entry_price + d


class ExecutionPort(Protocol):
    """
    What the downstream agent implements to execute actions. `enter` must
    return the resulting Position (with stop_price set); `set_stop` must update
    position.stop_price and set position.stop_at_cost when action.reason ==
    "cost"; `close` must flatten.

    下游 agent 实现的下单接口。`enter` 必须返回建立的 Position（含 stop_price）；`set_stop`
    必须更新 position.stop_price，且在 action.reason == "cost" 时置 stop_at_cost；`close` 必须
    平仓。
    """

    def enter(self, action: Action, ctx: StepContext) -> Position: ...
    def close(self, action: Action, ctx: StepContext) -> None: ...
    def set_stop(self, action: Action, ctx: StepContext) -> None: ...


class RecordingPort:
    """
    In-memory reference ExecutionPort: fills at the action price, keeps one
    Position, records every action. Used by the dry-run and by tests.

    内存版参考下单端：按动作价格成交、维护一个 Position、记录每个动作。供 dry-run 与测试使用。
    """

    def __init__(self) -> None:
        """
        Start flat with an empty action log.

        初始为空仓、空日志。
        """
        self.position: Optional[Position] = None
        self.log: list[Action] = []

    def apply(self, action: Action, ctx: StepContext) -> None:
        """
        Dispatch one action to enter / set_stop / close.

        把一个动作分发到 enter / set_stop / close。
        """
        self.log.append(action)
        {"enter": self.enter, "close": self.close, "set_stop": self.set_stop}[action.kind](action, ctx)

    def enter(self, action: Action, ctx: StepContext) -> Position:
        """
        Open a position at the action price with the given stop.

        按动作价格开仓并设置止损。
        """
        self.position = Position(
            instrument=ctx.instrument, direction=action.direction, entry_price=float(action.price),
            entry_time=ctx.now or datetime.now(), size=float(action.size or 0), stop_price=action.stop_price,
            stop_at_cost=False,
        )
        return self.position

    def close(self, action: Action, ctx: StepContext) -> None:
        """
        Flatten.

        平仓。
        """
        self.position = None

    def set_stop(self, action: Action, ctx: StepContext) -> None:
        """
        Move the stop; a "cost" move marks stop_at_cost.

        移动止损；原因为 "cost" 时标记 stop_at_cost。
        """
        if self.position is not None:
            self.position.stop_price = action.stop_price
            if action.reason == "cost":
                self.position.stop_at_cost = True


class StrategyDriverBase:
    """
    Runtime shared by every generated driver: state, built-in stop-hit test and
    the action constructors used by the generated `step()`.

    所有生成的 driver 共用的运行时：状态、内置的止损触发判断，以及生成的 `step()` 使用的动作
    构造器。
    """

    initial_state: str = "{initial_state}"
    # name -> (trigger event, mode, output type); filled by the generated subclass
    # 回调名 -> (触发事件, 模式, 输出类型)；由生成的子类填充
    callback_meta: dict[str, tuple[str, str, str]] = {}

    def __init__(self, callbacks: StrategyCallbacks, account: Account) -> None:
        """
        Bind the callbacks implementation and the account; start in the
        initial state with an empty signal cache.

        绑定回调实现与账户，置为初始状态，信号缓存为空。
        """
        self.callbacks = callbacks
        self.account = account
        self.state = self.initial_state
        self.cache = SignalCache()

    def step(self, ctx: StepContext) -> list[Action]:
        """
        Shorthand for a tick event.

        等价于一次 tick 事件。
        """
        return self.on_event("tick", ctx)

    def on_event(self, event: Event, ctx: StepContext) -> list[Action]:
        """
        Generated in the subclass: evaluate the flow for one event.

        由子类生成：对一个事件评估一遍 flow。
        """
        raise NotImplementedError

    def _call(self, name: str, event: str, **kwargs: Any) -> Any:
        """
        Invoke a callback on its trigger event and cache the result. For a
        callback scheduled `async`, a None result means "no fresh value yet"
        and the previous cached value is returned instead.

        在触发事件上调用回调并缓存结果。schedule 为 `async` 的回调返回 None 表示"尚无新值"，
        此时返回之前的缓存值。
        """
        result = getattr(self.callbacks, name)(**kwargs)
        mode = self.callback_meta.get(name, ("", "sync", ""))[1]
        if result is None and mode == "async":
            return self.cache.get(name)
        self.cache.put(name, result, event)
        return result

    def stop_hit(self, ctx: StepContext) -> bool:
        """
        Exit path one: the last price has reached the position's stop (long:
        at or below; short: at or above).

        出场路径一：最新价触及持仓止损（多头：不高于止损价；空头：不低于止损价）。
        """
        p = ctx.position
        if p is None or p.stop_price is None or ctx.last_price is None:
            return False
        return ctx.last_price <= p.stop_price if p.direction == "long" else ctx.last_price >= p.stop_price

    def _enter(self, rule_id: str, direction: Direction, entry_price: float, stop: "StopDistance | float",
               ctx: StepContext) -> Action:
        """
        Build the enter action: size from account risk, initial stop from the
        stop distance.

        构造开仓动作：按账户风险反算手数，按止损距离算初始止损价。
        """
        size = self.account.size_from_risk(entry_price, stop, ctx.instrument)
        for name, (_, _, otype) in self.callback_meta.items():
            if otype == "EntryDecision":
                self.cache.invalidate(name)  # a consumed entry signal must not re-fire from cache / 已用的入场信号不得再触发
        return Action(kind="enter", rule_id=rule_id, direction=direction, price=float(entry_price), size=size,
                      stop_price=stop_price_from(entry_price, direction, stop))

    def _move_stop_to_cost(self, rule_id: str, ctx: StepContext) -> Action:
        """
        Build the set_stop action that moves the stop to the entry price.

        构造把止损移到入场价的动作。
        """
        return Action(kind="set_stop", rule_id=rule_id, stop_price=float(ctx.position.entry_price), reason="cost")

    def _move_stop(self, rule_id: str, new_stop: float, ctx: StepContext) -> Optional[Action]:
        """
        Build a trailing set_stop action, enforcing "only tightens": a new stop
        that would loosen the current one is ignored (returns None).

        构造移动止损动作，并强制"只进不退"：会放松现有止损的新价位被忽略（返回 None）。
        """
        p = ctx.position
        if p is None or new_stop is None:
            return None
        cur = p.stop_price
        if cur is not None and ((p.direction == "long" and new_stop <= cur) or (p.direction == "short" and new_stop >= cur)):
            return None
        return Action(kind="set_stop", rule_id=rule_id, stop_price=float(new_stop), reason="trail")

    def _set_stop(self, rule_id: str, stop_price: float) -> Action:
        """
        Build an unconditional set_stop action.

        构造无条件设置止损的动作。
        """
        return Action(kind="set_stop", rule_id=rule_id, stop_price=float(stop_price), reason="set")

    def _close(self, rule_id: str, reason: str, ctx: StepContext) -> Action:
        """
        Build the close action for an exit path.

        构造某条出场路径的平仓动作。
        """
        p = ctx.position
        return Action(kind="close", rule_id=rule_id, direction=p.direction if p else None,
                      price=ctx.last_price, size=p.size if p else None, reason=reason)

@dataclass
class CachedSignal:
    """
    One callback result kept by SignalCache with the event and sequence
    number at which it was produced.

    SignalCache 保存的一个回调结果，附带产生它的事件及序号。
    """
    value: Any
    event: str
    seq: int


class SignalCache:
    """
    Latest result of every callback, keyed by callback name. Rules read from
    it on events that are not their trigger, and async callbacks that return
    None leave the cached value in place. `seq` counts events so staleness
    can be measured.

    每个回调的最新结果，按回调名索引。规则在非触发事件上从这里读值；返回 None 的异步回调
    保留缓存值。`seq` 对事件计数，便于衡量陈旧程度。
    """

    def __init__(self) -> None:
        """
        Start empty.

        初始为空。
        """
        self._items: dict[str, CachedSignal] = {}
        self.seq = 0

    def get(self, name: str) -> Any:
        """
        Cached value for a callback, or None when it has never been produced.

        某回调的缓存值；从未产生过则为 None。
        """
        item = self._items.get(name)
        return None if item is None else item.value

    def put(self, name: str, value: Any, event: str) -> None:
        """
        Store a fresh result.

        存入新结果。
        """
        self._items[name] = CachedSignal(value=value, event=event, seq=self.seq)

    def invalidate(self, name: str) -> None:
        """
        Forget a result (used after an entry so a stale entry signal cannot
        re-fire).

        清除某结果（入场后用，避免陈旧的入场信号再次触发）。
        """
        self._items.pop(name, None)

    def age(self, name: str) -> Optional[int]:
        """
        Number of events since the result was produced, or None.

        该结果产生以来经过的事件数；没有则为 None。
        """
        item = self._items.get(name)
        return None if item is None else self.seq - item.seq


@dataclass
class Action:
    """
    One instruction from the driver to the execution port. `kind` is enter /
    close / set_stop; `reason` distinguishes `set_stop` at cost ("cost") from a
    trailing move ("trail") and names the exit path for `close` ("stop",
    "reversal", ...). `rule_id` is the flow rule that produced it.

    driver 发给下单端的一条指令。`kind` 为 enter / close / set_stop；`reason` 区分移损至成本
    （"cost"）与移动止损（"trail"），并给出平仓原因（"stop"、"reversal"…）。`rule_id` 是产生
    它的 flow 规则。
    """
    kind: ActionKind
    rule_id: str
    direction: Optional[Direction] = None
    price: Optional[float] = None
    size: Optional[float] = None
    stop_price: Optional[float] = None
    reason: str = ""

    def label(self) -> str:
        """
        Short label used in traces and dry-run expectations: enter,
        move_stop_to_cost, move_stop, set_stop, close:<reason>.

        用于轨迹和 dry-run 期望值的短标签：enter、move_stop_to_cost、move_stop、set_stop、
        close:<原因>。
        """
        if self.kind == "enter":
            return "enter"
        if self.kind == "close":
            return f"close:{self.reason}" if self.reason else "close"
        return {"cost": "move_stop_to_cost", "trail": "move_stop"}.get(self.reason, "set_stop")



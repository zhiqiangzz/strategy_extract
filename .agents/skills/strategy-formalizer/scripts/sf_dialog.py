def cmd_add(args: argparse.Namespace) -> None:
    """
    Add one question (--question) or many (--batch file with a JSON list of
    {question, affects_terms?, affects_sections?}) as open entries, then
    print the new ids. Run this BEFORE asking the user.

    以 open 状态添加一个问题（--question）或多个问题（--batch 指向 JSON 列表文件，元素形如
    {question, affects_terms?, affects_sections?}），并打印新 id。请在向用户提问之前运行。
    """
    ws = resolve_workspace(args.workspace)
    data = load_dialog(ws, args.stage)
    items: list[dict] = []
    if args.batch:
        items = load_json(args.batch)
    if args.question:
        items.append({"question": args.question,
                      "affects_terms": [t for t in (args.affects_terms or "").split(",") if t],
                      "affects_sections": [s for s in (args.affects_sections or "").split(",") if s]})
    if not items:
        fail("nothing to add: give --question or --batch", "缺少 --question 或 --batch")
    for it in items:
        e = add_question(data, it["question"], it.get("affects_terms") or [], it.get("affects_sections") or [],
                         args.round)
        say(f"added {e['id']} (round {e['round']})", "已添加问题")
    save_dialog(ws, args.stage, data)


def cmd_answer(args: argparse.Namespace) -> None:
    """
    Store the user's answer for an entry (status -> answered) and optionally a
    resolution. Run this IMMEDIATELY after the user replies, before applying
    the answer anywhere.

    保存用户对某问题的回答（状态 -> answered），可同时给出 resolution。请在用户回答后
    立即运行，然后再去落实这个回答。
    """
    ws = resolve_workspace(args.workspace)
    data = load_dialog(ws, args.stage)
    e = find(data, args.id)
    e["answer_zh"] = args.answer.strip()
    e["answered_at"] = now_iso()
    e["status"] = "answered"
    if args.resolution:
        e["resolution"] = args.resolution.strip()
    save_dialog(ws, args.stage, data)
    say(f"{args.id} answered", f"{args.id} 已记录回答")


def cmd_close(args: argparse.Namespace) -> None:
    """
    Mark an answered entry closed once its consequence has been written into
    the summary / term file; --resolution records what changed.

    当回答已落实到总结或术语文件后，把条目标记为 closed；--resolution 记录改动内容。
    """
    ws = resolve_workspace(args.workspace)
    data = load_dialog(ws, args.stage)
    e = find(data, args.id)
    if e["status"] == "open" and not args.force:
        fail(f"{args.id} has no answer yet; use --force to close anyway", "尚未回答，强制关闭请加 --force")
    e["status"] = "closed"
    if args.resolution:
        e["resolution"] = args.resolution.strip()
    save_dialog(ws, args.stage, data)
    say(f"{args.id} closed", f"{args.id} 已关闭")


def cmd_to_md(args: argparse.Namespace) -> None:
    """
    Regenerate <stage>_dialog.md from the json.

    根据 json 重新生成 <stage>_dialog.md。
    """
    ws = resolve_workspace(args.workspace)
    data = load_dialog(ws, args.stage)
    _, mp = paths(ws, args.stage)
    write_text(mp, render_md(data))
    say(f"wrote {relpath(mp)}", "已写出 markdown")


def cmd_from_md(args: argparse.Namespace) -> None:
    """
    Merge answers / resolutions / statuses the user typed into the .md back
    into the json (ids and timestamps are preserved; unknown ids are
    reported, not created). The md is then re-rendered.

    把用户在 .md 中填写的回答 / resolution / 状态合并回 json（保留 id 与时间戳；未知 id
    只报告不创建），然后重新渲染 md。
    """
    ws = resolve_workspace(args.workspace)
    data = load_dialog(ws, args.stage)
    _, mp = paths(ws, args.stage)
    parsed = parse_md(read_text(mp))
    by_id = {e["id"]: e for e in data["entries"]}
    changed = 0
    for p in parsed:
        e = by_id.get(p["id"])
        if e is None:
            say(f"unknown id {p['id']} in md ignored", "md 中出现未知 id，已忽略")
            continue
        if p["status"] not in DIALOG_STATUSES:
            fail(f"bad status {p['status']} on {p['id']}", "状态值非法")
        before = (e["answer_zh"], e["resolution"], e["status"], e["question_zh"])
        if p["answer_zh"] and p["answer_zh"] != e["answer_zh"]:
            e["answer_zh"] = p["answer_zh"]
            e["answered_at"] = now_iso()
        e["resolution"] = p["resolution"] if p["resolution"] else e["resolution"]
        e["question_zh"] = p["question_zh"] or e["question_zh"]
        e["status"] = p["status"]
        e["affects"] = p["affects"]
        if before != (e["answer_zh"], e["resolution"], e["status"], e["question_zh"]):
            changed += 1
    save_dialog(ws, args.stage, data)
    say(f"merged md into json; {changed} entries changed", f"已合并，{changed} 条有变化")


def cmd_list(args: argparse.Namespace) -> None:
    """
    Print entries (optionally only open ones) in one line each.

    逐行打印条目（可只看 open 的）。
    """
    ws = resolve_workspace(args.workspace)
    data = load_dialog(ws, args.stage)
    for e in data["entries"]:
        if args.open and e["status"] != "open":
            continue
        q = e["question_zh"].replace("\n", " ")
        print(f"{e['id']} r{e.get('round')} [{e['status']}] {q[:80]}")


def build_parser() -> argparse.ArgumentParser:
    """
    Build the CLI.

    构建命令行。
    """
    p = argparse.ArgumentParser(description="dialog audit trail / 对话留痕")
    p.add_argument("--workspace", "-w")
    p.add_argument("--stage", "-s", required=True, choices=DIALOG_STAGES)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("add")
    s.add_argument("--question", "-q")
    s.add_argument("--batch", help="json file with a list of {question, affects_terms, affects_sections}")
    s.add_argument("--affects-terms", help="comma separated term ids")
    s.add_argument("--affects-sections", help="comma separated summary section keys")
    s.add_argument("--round", type=int)
    s.set_defaults(func=cmd_add)

    s = sub.add_parser("answer")
    s.add_argument("id")
    s.add_argument("--answer", "-a", required=True)
    s.add_argument("--resolution", "-r")
    s.set_defaults(func=cmd_answer)

    s = sub.add_parser("close")
    s.add_argument("id")
    s.add_argument("--resolution", "-r")
    s.add_argument("--force", action="store_true")
    s.set_defaults(func=cmd_close)

    sub.add_parser("to-md").set_defaults(func=cmd_to_md)
    sub.add_parser("from-md").set_defaults(func=cmd_from_md)
    s = sub.add_parser("list")
    s.add_argument("--open", action="store_true")
    s.set_defaults(func=cmd_list)
    return p


def main(argv: list[str] | None = None) -> None:
    """
    CLI entry point.

    命令行入口。
    """
    args = build_parser().parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
